def from_maps(objects, hom, name):
    """A concrete category: hom(x, y) lists the maps x → y as tuples (images of range(|x|));
    composition is composition of functions. Objects are sizes."""
    arrows, index = [], {}
    for x in objects:
        for y in objects:
            for m in hom(x, y):
                index[(x, y, m)] = len(arrows)
                arrows.append((x, y))
    maps = {i: k for k, i in index.items()}
    comp = {}
    for f, (x, y, mf) in maps.items():
        for g, (y2, z, mg) in maps.items():
            if y2 == y:
                comp[(g, f)] = index[(x, z, tuple(mg[i] for i in mf))]
    return FinCat(objects, arrows, comp, name)


def monotone(x, y):
    return [m for m in itertools.product(range(y), repeat=x)
            if all(m[i] <= m[i + 1] for i in range(x - 1))]


def deck_simplex(n, augmented=False):
    """Δ≤n (objects [0..n] as sizes 1..n+1); with `augmented`, the empty ordinal too."""
    objs = list(range(0 if augmented else 1, n + 2))
    return from_maps(objs, monotone, f"Delta_{'+' if augmented else ''}<= {n}")


def deck_semisimplex(n):
    """Δ_inj≤n: injective monotone maps (semi-simplicial sets truncated at n)."""
    return from_maps(range(1, n + 2), lambda x, y: [m for m in monotone(x, y)
                                                    if len(set(m)) == x], f"Delta_inj<= {n}")


def deck_finset(n, kind="all"):
    """FinSet on sizes 1..n: all maps, injections (FI) or surjections (FS); presheaves are
    symmetric simplicial sets truncated, FI-sets and FS-sets."""
    def hom(x, y):
        ms = itertools.product(range(y), repeat=x)
        if kind == "inj":
            return [m for m in ms if len(set(m)) == x]
        if kind == "surj":
            return [m for m in ms if len(set(m)) == y]
        return list(ms)
    return from_maps(range(1, n + 1), hom, f"FinSet[{kind}]<= {n}")


def deck_poset(elements, le, name):
    """A finite poset as a category: one arrow x → y when x ≤ y."""
    arrows = [(x, y) for x in elements for y in elements if le(x, y)]
    idx = {a: i for i, a in enumerate(arrows)}
    comp = {(idx[(y, z)], idx[(x, y)]): idx[(x, z)] for (x, y) in arrows for (y2, z) in arrows
            if y2 == y}
    return FinCat(elements, arrows, comp, name)


def deck_free(vertices, edges, name):
    """The free category on a finite acyclic quiver: arrows are paths (tuples of edges)."""
    paths = [(v,) for v in vertices]  # identity paths as (v,)

    def ends(p):
        if len(p) == 1 and p[0] in vertices and not isinstance(p[0], tuple):
            return p[0], p[0]
        return edges[p[0]][0], edges[p[-1]][1]
    frontier = [(e,) for e in range(len(edges))]
    allp = []
    while frontier:
        allp += frontier
        frontier = [p + (e,) for p in frontier for e in range(len(edges))
                    if edges[p[-1]][1] == edges[e][0]]
        assert len(allp) < 5000, "quiver not acyclic"
    ids = {v: i for i, v in enumerate(vertices)}
    arrows = [(v, v) for v in vertices] + [(edges[p[0]][0], edges[p[-1]][1]) for p in allp]
    pidx = {p: len(vertices) + i for i, p in enumerate(allp)}
    comp = {}
    n = len(arrows)
    for f in range(n):
        for g in range(n):
            if arrows[f][1] != arrows[g][0]:
                continue
            if f < len(vertices):
                comp[(g, f)] = g
            elif g < len(vertices):
                comp[(g, f)] = f
            else:
                comp[(g, f)] = pidx[allp[f - len(vertices)] + allp[g - len(vertices)]]
    return FinCat(vertices, arrows, comp, name)


def deck_monoid(table, name="B M"):
    n = len(table)
    arrows = [(0, 0)] * n
    comp = {(g, f): table[g][f] for f in range(n) for g in range(n)}
    return FinCat([0], arrows, comp, name)


def decks():
    out = []
    for n in (1, 2):
        out.append((f"Δ≤{n}", "truncated simplicial sets" + (" (reflexive graphs)" if n == 1 else ""),
                    deck_simplex(n)))
        out.append((f"Δ₊≤{n}", "augmented truncated simplicial sets", deck_simplex(n, True)))
        out.append((f"Δinj≤{n}", "semi-simplicial sets, truncated" + (" (graphs)" if n == 1 else ""),
                    deck_semisimplex(n)))
    for n in (2, 3):
        out.append((f"FinSet≤{n}", "symmetric simplicial sets, truncated", deck_finset(n)))
        out.append((f"FI≤{n}", "FI-sets (injections), truncated", deck_finset(n, "inj")))
        out.append((f"FS≤{n}", "FS-sets (surjections), truncated", deck_finset(n, "surj")))
    for n in (2, 3, 4):
        out.append((f"[{n}] chain", f"sequences of {n} sets and maps", deck_poset(
            list(range(n)), lambda a, b: a <= b, f"chain {n}")))
    for k in (2, 3):
        els = list(range(2 ** k))
        out.append((f"2^{k}", f"presheaves on the Boolean lattice of a {k}-set",
                    deck_poset(els, lambda a, b: a & b == a, f"2^{k}")))
    # presheaves are contravariant: a bottom element gives cospans of sets, a top one spans
    out.append(("•←∘→•", "cospans of sets X → Z ← Y", deck_poset(["l", "a", "r"],
                lambda a, b: a == b or (a == "a"), "bottom")))
    out.append(("•→∘←•", "spans of sets X ← R → Y (binary relations)", deck_poset(
        ["l", "a", "r"], lambda a, b: a == b or (b == "a"), "top")))
    out.append(("V⇇E", "directed graphs", deck_free(["V", "E"], [("V", "E"), ("V", "E")], "graphs")))
    out.append(("bipartite", "hypergraphs as incidence structures: points, blocks, flags",
                deck_free(["P", "B", "F"], [("P", "F"), ("B", "F")], "incidence")))
    return out


def check():
    here = os.path.dirname(os.path.abspath(__file__))
    data = json.load(open(os.path.join(here, "monoids-6.json")))
    bad = 0
    for order in ("1", "2", "3", "4"):
        for m in data[order]:
            inv = deck_monoid(m["table"]).invariants()
            ref = {"groupoid": m["group"], "ore": m["ore"], "points": m["points"],
                   "subtopoi": m["subtopoi"]}
            got = {k: inv[k] for k in ref}
            if got != ref:
                bad += 1
                print("mismatch", m["table"], got, ref)
        print(f"order {order}: {len(data[order])} monoids checked", flush=True)
    return bad


def main():
    if "--check" in sys.argv:
        bad = check()
        print("check:", "ok" if not bad else f"{bad} mismatches")
        if bad:
            sys.exit(1)
    here = os.path.dirname(os.path.abspath(__file__))
    rows = []
    for short, presheaves, cat in decks():
        inv = cat.invariants()
        rows.append({"deck": short, "presheaves": presheaves, **inv})
        print(f"{short:12} {presheaves[:48]:48} groupoid={inv['groupoid']!s:5} ore={inv['ore']!s:5}"
              f" points={inv['points']:3} subtopoi={inv['subtopoi']}", flush=True)
    with open(os.path.join(here, "categories.json"), "w") as f:
        json.dump(rows, f, ensure_ascii=False, indent=1)


if __name__ == "__main__":
    main()
