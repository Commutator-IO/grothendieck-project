#!/usr/bin/env python3
"""An atlas of finite decks: small finite categories C, with the invariants of PSh(C) that the
arches of the article read on C.

    python3 docs/bridges/atlas/categories.py            # all decks below, to categories.json
    python3 docs/bridges/atlas/categories.py --check    # compare with monoids-6.json first

A category is given by its arrows: each arrow has a domain and a codomain, and `comp[g, f]` is
g ∘ f (f first) when cod f = dom g. The decks are built by the functions `deck_*` below.

Invariants (arch of the article in brackets):
  groupoid   every arrow is invertible                          [Boolean]
  ore        right Ore: for f : A → X and g : B → X there are h : D → A, k : D → B
             with f ∘ h = g ∘ k                                 [De Morgan]
  points     isomorphism classes of objects of the Karoubi envelope (idempotents e ≅ e' when
             e = b ∘ a and e' = a ∘ b for some a ∈ e' C e, b ∈ e C e')   [essential points]
  subtopoi   number of Grothendieck topologies on C             [subtopoi]

Topologies are enumerated as joins: every topology is generated by its covering sieves, so the
lattice of topologies is the closure of the topologies generated by one sieve under finite joins.
The check against monoids-6.json compares the four invariants on every monoid of order <= 4
(as the one-object category B M) with the monoid-specific formulas of monoids.py.
"""
import itertools
import json
import os
import sys


class FinCat:
    def __init__(self, objects, arrows, comp, name=""):
        # arrows: list of (dom, cod); comp: dict (g, f) -> h for cod f = dom g
        self.name = name
        self.objects = list(objects)
        self.arrows = list(arrows)
        self.comp = comp
        self.n = len(arrows)
        self.ident = {}
        for a, (d, c) in enumerate(arrows):
            if d == c and all(comp[(a, f)] == f for f in range(self.n) if arrows[f][1] == d) \
                    and all(comp[(g, a)] == g for g in range(self.n) if arrows[g][0] == d):
                self.ident[d] = a
        assert set(self.ident) == set(self.objects), f"{name}: missing identities"
        self.into = {x: [f for f in range(self.n) if arrows[f][1] == x] for x in self.objects}
        self.check_assoc()

    def dom(self, f):
        return self.arrows[f][0]

    def cod(self, f):
        return self.arrows[f][1]

    def c(self, g, f):
        return self.comp[(g, f)]

    def check_assoc(self):
        for f in range(self.n):
            for g in range(self.n):
                if self.cod(f) != self.dom(g):
                    continue
                gf = self.c(g, f)
                assert self.arrows[gf] == (self.dom(f), self.cod(g)), (self.name, g, f)
                for h in range(self.n):
                    if self.cod(g) == self.dom(h):
                        assert self.c(h, gf) == self.c(self.c(h, g), f), (self.name, h, g, f)

    # --- the four invariants -------------------------------------------------------------
    def groupoid(self):
        return all(any(self.cod(f) == self.dom(g) and self.dom(f) == self.cod(g)
                       and self.c(g, f) == self.ident[self.dom(f)]
                       and self.c(f, g) == self.ident[self.cod(f)] for g in range(self.n))
                   for f in range(self.n))

    def ei(self):
        """Every endomorphism is invertible."""
        return all(any(self.arrows[g] == self.arrows[f] and self.c(g, f) == self.ident[self.dom(f)]
                       and self.c(f, g) == self.ident[self.dom(f)] for g in range(self.n))
                   for f in range(self.n) if self.dom(f) == self.cod(f))

    def ore(self):
        for x in self.objects:
            for f in self.into[x]:
                for g in self.into[x]:
                    if not any(self.cod(h) == self.dom(f) and self.cod(k) == self.dom(g)
                               and self.dom(h) == self.dom(k) and self.c(f, h) == self.c(g, k)
                               for h in range(self.n) for k in range(self.n)):
                        return False
        return True

    def karoubi_classes(self):
        idem = [e for e in range(self.n) if self.dom(e) == self.cod(e) and self.c(e, e) == e]
        parent = {e: e for e in idem}

        def find(e):
            while parent[e] != e:
                e = parent[e]
            return e
        for e in idem:
            for e2 in idem:
                x, y = self.dom(e), self.dom(e2)
                iso = any(self.c(self.c(e2, a), e) == a and self.c(self.c(e, b), e2) == b
                          and self.c(b, a) == e and self.c(a, b) == e2
                          for a in range(self.n) if self.arrows[a] == (x, y)
                          for b in range(self.n) if self.arrows[b] == (y, x))
                if iso:
                    parent[find(e)] = find(e2)
        return len({find(e) for e in idem})

    # --- sieves and topologies -------------------------------------------------------------
    def sieves(self, x):
        """All sieves on x, as frozensets of arrows into x closed under precomposition."""
        gen = {}
        for f in self.into[x]:
            gen[f] = frozenset(self.c(f, h) for h in range(self.n) if self.cod(h) == self.dom(f))
        out = {frozenset()}
        frontier = [frozenset()]
        while frontier:
            new = []
            for s in frontier:
                for f in self.into[x]:
                    if f not in s:
                        t = s | gen[f]
                        if t not in out:
                            out.add(t)
                            new.append(t)
            frontier = new
        return out

    def pullback(self, f, s):
        return frozenset(h for h in self.into[self.dom(f)] if self.c(f, h) in s)

    def setup_sieves(self):
        if hasattr(self, "_sv"):
            return
        self._sv = {x: sorted(self.sieves(x), key=lambda s: (len(s), sorted(s)))
                    for x in self.objects}
        self._idx = [(x, s) for x in self.objects for s in self._sv[x]]
        self._pos = {p: i for i, p in enumerate(self._idx)}
        self._max = {x: frozenset(self.into[x]) for x in self.objects}

    def close(self, bits):
        """Smallest topology containing the covering sieves in `bits` (a set of indices)."""
        J = set(bits) | {self._pos[(x, self._max[x])] for x in self.objects}
        changed = True
        while changed:
            changed = False
            for i in list(J):
                x, s = self._idx[i]
                for f in range(self.n):
                    if self.cod(f) == x:
                        j = self._pos[(self.dom(f), self.pullback(f, s))]
                        if j not in J:
                            J.add(j)
                            changed = True
            for x in self.objects:
                covers = [s for (y, s) in (self._idx[i] for i in J) if y == x]
                for r in self._sv[x]:
                    i = self._pos[(x, r)]
                    if i in J:
                        continue
                    if any(all(self._pos[(self.dom(f), self.pullback(f, r))] in J for f in s)
                           for s in covers):
                        J.add(i)
                        changed = True
        return frozenset(J)

    def topologies(self, limit=200000):
        self.setup_sieves()
        bottom = self.close(set())
        principal = {self.close({i}) for i in range(len(self._idx))}
        tops = {bottom} | principal
        frontier = list(tops)
        while frontier:
            new = []
            for t in frontier:
                for p in principal:
                    if not p <= t:
                        u = self.close(t | p)
                        if u not in tops:
                            tops.add(u)
                            new.append(u)
                            if len(tops) > limit:
                                raise RuntimeError(f"{self.name}: more than {limit} topologies")
            frontier = new
        return tops

    def invariants(self):
        return {
            "objects": len(self.objects),
            "arrows": self.n,
            "groupoid": self.groupoid(),
            "ore": self.ore(),
            "EI": self.ei(),
            "points": self.karoubi_classes(),
            "subtopoi": len(self.topologies()),
        }


