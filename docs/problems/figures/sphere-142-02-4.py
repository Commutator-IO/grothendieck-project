import math, sys
R=30.0; alpha=math.radians(30)   # camera elevation
def proj(lat,lon):
    la,lo=math.radians(lat),math.radians(lon)
    x=math.cos(la)*math.sin(lo); y=math.sin(la); z=math.cos(la)*math.cos(lo)
    y2=y*math.cos(alpha)-z*math.sin(alpha); z2=y*math.sin(alpha)+z*math.cos(alpha)
    return R*x,R*y2,z2
L={'Q_1':-65,'Q_\\infty':15,'Q_0':80}
def arc(a,b,bulge,n=60,through_back=False):
    la,lb=L[a],L[b]
    if through_back:  # go the long way, through longitude 180
        lb = lb-360 if lb>la else lb+360
    pts=[]
    for i in range(n+1):
        t=i/n; lon=la+(lb-la)*t; lat=bulge*math.sin(math.pi*t)
        pts.append(proj(lat,lon))
    return pts
def segs(pts):
    out=[];cur=[pts[0]];vis=pts[0][2]>=0
    for p in pts[1:]:
        v=p[2]>=0
        if v!=vis: out.append((vis,cur)); cur=[cur[-1]]; vis=v
        cur.append(p)
    out.append((vis,cur)); return out
def path(pts): return ' -- '.join(f'({p[0]:.2f},{p[1]:.2f})' for p in pts)
B=19
LAB={'\\tilde a_0^{+}':(B+8,-25),'\\tilde a_0^{-}':(-B-8,-25),'\\tilde a_1^{+}':(B+8,47),'\\tilde a_1^{-}':(-B-8,47),'\\tilde a_\\infty^{+}':(B+9,-172),'\\tilde a_\\infty^{-}':(-B+2,200)}
arcs=[ # (from,to,bulge,back,label,label side)
 ('Q_\\infty','Q_1', B,False,'\\tilde a_0^{+}'),
 ('Q_1','Q_\\infty',-B,False,'\\tilde a_0^{-}'),
 ('Q_0','Q_\\infty', B,False,'\\tilde a_1^{+}'),
 ('Q_\\infty','Q_0',-B,False,'\\tilde a_1^{-}'),
 ('Q_1','Q_0', B,True,'\\tilde a_\\infty^{+}'),
 ('Q_0','Q_1',-B,True,'\\tilde a_\\infty^{-}'),
]
o=[]
o.append('% Figure 142/02-4 (folder 142, archive page 27), redrawn for this article as a sphere: the')
o.append('% three cusps Q_0, Q_1, Q_infty on the real great circle of P^1, and for each pair of cusps two')
o.append('% arcs, one in each hemisphere (+ north, - south), oriented as on the page. Generated by')
o.append('% docs/problems/figures/sphere-142-02-4.py; front parts solid, hidden parts dashed.')
o.append('\\begin{tikzpicture}[x=1mm,y=1mm,line cap=round,line join=round,font=\\small,')
o.append('  arc/.style={thick,black!80}, hid/.style={black!45,dashed}, eq/.style={black!35,thin}]')
o.append(f'\\shade[ball color=black!4,opacity=0.9] (0,0) circle ({R});')
o.append(f'\\draw[black!60] (0,0) circle ({R});')
eq=[proj(0,l) for l in range(-180,181,3)]
for v,s in segs(eq):
    o.append(f'\\draw[{"eq" if v else "eq,dashed"}] {path(s)};')
for a,b,bul,back,lab in arcs:
    pts=arc(a,b,bul,through_back=back)
    for v,s in segs(pts):
        o.append(f'\\draw[{"arc" if v else "hid"}] {path(s)};')
    m=len(pts)//2; p,q=pts[m-1],pts[m+1]
    st='arc' if pts[m][2]>=0 else 'hid'
    o.append(f'\\draw[{st},-{{Stealth[length=2.6mm]}}] ({p[0]:.2f},{p[1]:.2f}) -- ({pts[m][0]:.2f},{pts[m][1]:.2f});')
    # label slightly outward from the arc midpoint
    lat=bul*1.55; lon=(L[a]+(L[b]-(360 if back and L[b]>L[a] else (-360 if back else 0)) - L[a])/2) if False else None
    mx,my,mz=pts[m]
    import math as mm
    d=mm.hypot(mx,my) or 1
    sgn=1 if bul>0 else -1
    lx,ly,_=proj(*LAB[lab])
    col='' if mz>=0 else ',black!55'
    o.append(f'\\node[inner sep=1pt{col}] at ({lx:.2f},{ly:.2f}) {{${lab}$}};')
for k,lon in L.items():
    x,y,z=proj(0,lon)
    o.append(f'\\fill ({x:.2f},{y:.2f}) circle (1.1);')
    dx = -4.5 if lon<0 else (4.8 if lon>40 else 0)
    dy = -4.2 if -10<lon<40 else 0
    o.append(f'\\node at ({x+dx:.2f},{y+dy:.2f}) {{${k}$}};')
o.append('\\end{tikzpicture}')
open(sys.argv[1],'w').write('\n'.join(o)+'\n')
