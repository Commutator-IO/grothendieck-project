#!/usr/bin/env node
/**
 * Compiles the figures redrawn under #73 so that the transcriptions show them.
 *
 *   npm run drawings          every folder with transcripts/<cote>/drawings/
 *   npm run drawings -- 119   only these folders
 *
 * Each `transcripts/<cote>/drawings/<id>.tex` is a standalone TikZ document. It
 * is compiled once by tectonic, and poppler's pdftocairo turns the PDF into an
 * SVG. The results are kept by the hash of the source in
 * node_modules/.cache/drawings, so an unchanged figure is never recompiled.
 *
 * Three outputs, none of them committed:
 *   - public/transcripts/<cote>/drawings/<id>.svg, which the reading view
 *     shows above the transcriber's description (render.mjs);
 *   - transcripts/<cote>/drawings/<id>.pdf, which the batch PDF includes;
 *   - transcripts/<cote>/drawings/<batch>.map.tex, which tells the preamble's
 *     \drawing which figure its k-th occurrence in that batch is.
 *
 * Like the reading views, these reproduce part of the work and are built only
 * when the deploy builds transcriptions (RENDER_TRANSCRIPTS).
 */
import { execFile } from 'node:child_process';
import { createHash } from 'node:crypto';
import { copyFile, mkdir, mkdtemp, readdir, readFile, rm, writeFile } from 'node:fs/promises';
import { existsSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join, resolve } from 'node:path';
import { promisify } from 'node:util';
import { drawingMap, folderDrawings } from './lib/drawing-map.mjs';

const exec = promisify(execFile);
const root = resolve(import.meta.dirname, '..');
const SOURCE = resolve(root, 'transcripts');
const OUT = resolve(root, 'public/transcripts');
const CACHE = process.env.DRAWINGS_CACHE ?? resolve(root, 'node_modules/.cache/drawings');

const only = process.argv.slice(2).filter((a) => !a.startsWith('--'));
const folders = (await readdir(SOURCE, { withFileTypes: true }))
  .filter((d) => d.isDirectory() && existsSync(resolve(SOURCE, d.name, 'drawings', 'drawings.json')))
  .map((d) => d.name)
  .filter((f) => !only.length || only.includes(f));

await mkdir(CACHE, { recursive: true });
const work = await mkdtemp(join(tmpdir(), 'drawings-'));
let built = 0;
let reused = 0;
const failed = [];

async function compile(folder, d) {
  const src = resolve(SOURCE, folder, 'drawings', `${d.id}.tex`);
  if (!existsSync(src)) return false;
  const key = createHash('sha256').update(await readFile(src)).digest('hex').slice(0, 16);
  const pdf = resolve(CACHE, `${key}.pdf`);
  const svg = resolve(CACHE, `${key}.svg`);
  if (!existsSync(pdf) || !existsSync(svg)) {
    const dir = await mkdtemp(join(work, 'd-'));
    const run = () => exec('tectonic', ['-X', 'compile', src, '--outdir', dir]);
    try {
      // Twice: a cold tectonic cache can fail the first document (see pdf.mjs).
      try { await run(); } catch { await run(); }
      await exec('pdftocairo', ['-svg', resolve(dir, `${d.id}.pdf`), svg]);
      await copyFile(resolve(dir, `${d.id}.pdf`), pdf);
      built++;
    } catch (e) {
      const out = `${e.stdout ?? ''}\n${e.stderr ?? ''}`;
      failed.push(`${folder}/${d.id}: ${(/(?:^|\n)(!.*|error:.*)/.exec(out)?.[1] ?? e.message).slice(0, 200)}`);
      return false;
    }
  } else reused++;
  await mkdir(resolve(OUT, folder, 'drawings'), { recursive: true });
  await copyFile(svg, resolve(OUT, folder, 'drawings', `${d.id}.svg`));
  await copyFile(pdf, resolve(SOURCE, folder, 'drawings', `${d.id}.pdf`));
  return true;
}

for (const folder of folders) {
  const dir = resolve(SOURCE, folder);
  const ok = new Set();
  const all = folderDrawings(dir).filter((d) => d.status !== 'failed');
  // Four at a time: tectonic is mostly waiting on its own start-up.
  for (let i = 0; i < all.length; i += 4) {
    const batch = all.slice(i, i + 4);
    const res = await Promise.all(batch.map((d) => compile(folder, d)));
    batch.forEach((d, j) => res[j] && ok.add(d.id));
  }
  for (const file of (await readdir(dir)).filter((f) => /^batch-\d+\.fr\.tex$/.test(f))) {
    const map = drawingMap(dir, file, await readFile(resolve(dir, file), 'utf8'));
    const lines = map
      .map((d, k) => (d && ok.has(d.id) ? `\\grothDrawingFile{${k + 1}}{${d.id}}` : null))
      .filter(Boolean);
    const target = resolve(dir, 'drawings', file.replace(/\.tex$/, '.map.tex'));
    if (lines.length) await writeFile(target, `% Generated by scripts/drawings.mjs — do not edit.\n${lines.join('\n')}\n`);
    else await rm(target, { force: true });
  }
}

await rm(work, { recursive: true, force: true });
console.log(`${folders.length} folders: ${built} drawings compiled, ${reused} reused from the cache, ${failed.length} failed`);
for (const f of failed) console.log(`  ⚠ ${f}`);
