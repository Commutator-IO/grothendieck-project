"""Search for a non-effective finite equivalence relation on a finite k-scheme (problems paper, Problem 14).

X = Spec A, A a finite-dimensional commutative F_p-algebra given by structure constants.
A closed subscheme R of X x X is an ideal I of A (x) A.  R is an equivalence relation iff
  reflexive:   I is contained in ker(mu : A (x) A -> A),
  symmetric:   sigma(I) = I,
  transitive:  p13(I) is contained in I (x) A + A (x) I  inside A (x) A (x) A.
B = A^R = {a : a(x)1 - 1(x)a in I}.  R is effective iff I = J_B, the ideal generated by the b(x)1 - 1(x)b.
Always J_B is contained in I.  A counterexample is an equivalence relation with J_B strictly inside I.

Method: take a random ideal I0 inside ker(mu); E = the largest equivalence relation inside I0, obtained by
iterating I <- I cap sigma(I) cap p13^{-1}(I(x)A + A(x)I) until it stabilises; then test E = J_{A^E}.
usage: python3 search.py P TRIALS SEED
"""
import itertools, random, sys

P = int(sys.argv[1]) if len(sys.argv) > 1 else 2
TRIALS = int(sys.argv[2]) if len(sys.argv) > 2 else 200
random.seed(int(sys.argv[3]) if len(sys.argv) > 3 else 1)

# ---------- linear algebra over F_P (vectors are tuples of ints) ----------
def rref(rows, n):
    rows = [list(r) for r in rows]
    piv = []
    r = 0
    for c in range(n):
        k = next((i for i in range(r, len(rows)) if rows[i][c] % P), None)
        if k is None:
            continue
        rows[r], rows[k] = rows[k], rows[r]
        inv = pow(rows[r][c], P - 2, P)
        rows[r] = [x * inv % P for x in rows[r]]
        for i in range(len(rows)):
            if i != r and rows[i][c] % P:
                f = rows[i][c]
                rows[i] = [(a - f * b) % P for a, b in zip(rows[i], rows[r])]
        piv.append(c)
        r += 1
        if r == len(rows):
            break
    return [tuple(x) for x in rows[:r]], piv

def span(rows, n):
    return rref(rows, n)[0]

def contains(basis, v, n):
    return len(span(list(basis) + [v], n)) == len(basis)

def nullspace(rows, n):
    """vectors x with M x = 0, M given by rows"""
    R, piv = rref(rows, n)
    free = [c for c in range(n) if c not in piv]
    out = []
    for f in free:
        x = [0] * n
        x[f] = 1
        for i, c in enumerate(piv):
            x[c] = (-R[i][f]) % P
        out.append(tuple(x))
    return out

def intersect(U, V, n):
    """U cap V for subspaces given by bases"""
    if not U or not V:
        return []
    # solve sum a_i u_i = sum b_j v_j
    m = len(U) + len(V)
    rows = [[(U[i][c] if i < len(U) else -V[i - len(U)][c]) % P for i in range(m)] for c in range(n)]
    sols = nullspace(rows, m)
    vecs = [tuple(sum(s[i] * U[i][c] for i in range(len(U))) % P for c in range(n)) for s in sols]
    return span(vecs, n)

def preimage(f_cols, V, n_in, n_out):
    """{x in F^n_in : f(x) in V}, f given by images of basis vectors"""
    # complement test: x maps into V iff annihilators of V kill f(x)
    ann = nullspace(V, n_out) if V else [tuple(1 if i == j else 0 for i in range(n_out)) for j in range(n_out)]
    rows = [[sum(a[k] * f_cols[j][k] for k in range(n_out)) % P for j in range(n_in)] for a in ann]
    if not rows:
        return [tuple(1 if i == j else 0 for i in range(n_in)) for j in range(n_in)]
    return span(nullspace(rows, n_in), n_in)

# ---------- algebras ----------
class Alg:
    def __init__(self, d, mul):
        self.d = d        # basis e_0 = 1, ..., e_{d-1}
        self.mul = mul    # mul[i][j] = vector of e_i e_j

def monomial_alg(nvars, exps_ok):
    """k[x_1..x_nvars] / monomials not in the order ideal exps_ok (a down-closed finite set containing 0)"""
    mons = sorted(exps_ok, key=lambda e: (sum(e), e))
    idx = {m: i for i, m in enumerate(mons)}
    d = len(mons)
    mul = [[None] * d for _ in range(d)]
    for i, a in enumerate(mons):
        for j, b in enumerate(mons):
            c = tuple(x + y for x, y in zip(a, b))
            v = [0] * d
            if c in idx:
                v[idx[c]] = 1
            mul[i][j] = tuple(v)
    return Alg(d, mul)

def down_closed(nvars, maxdeg, extra_kill=()):
    ok = [e for e in itertools.product(range(maxdeg + 1), repeat=nvars) if sum(e) <= maxdeg]
    ok = set(ok)
    for k in extra_kill:
        ok = {e for e in ok if not all(x >= y for x, y in zip(e, k))}
    return ok

def tensor(A, Bk):
    d = A.d * Bk.d
    def ix(i, j):
        return i * Bk.d + j
    mul = [[None] * d for _ in range(d)]
    for i1, j1, i2, j2 in itertools.product(range(A.d), range(Bk.d), range(A.d), range(Bk.d)):
        u, w = A.mul[i1][i2], Bk.mul[j1][j2]
        v = [0] * d
        for a in range(A.d):
            if u[a]:
                for b in range(Bk.d):
                    if w[b]:
                        v[ix(a, b)] = (v[ix(a, b)] + u[a] * w[b]) % P
        mul[ix(i1, j1)][ix(i2, j2)] = tuple(v)
    return Alg(d, mul)

def times(M, x, y):
    out = [0] * M.d
    for i in range(M.d):
        if x[i]:
            for j in range(M.d):
                if y[j]:
                    m = M.mul[i][j]
                    for k in range(M.d):
                        if m[k]:
                            out[k] = (out[k] + x[i] * y[j] * m[k]) % P
    return tuple(out)

def ideal(M, gens):
    basis_vecs = [tuple(1 if i == j else 0 for i in range(M.d)) for j in range(M.d)]
    return span([times(M, g, b) for g in gens for b in basis_vecs], M.d)

def e(n, i):
    v = [0] * n
    v[i] = 1
    return tuple(v)

def run(A, name):
    d = A.d
    AA = tensor(A, A)
    AAA = tensor(AA, A)
    n2, n3 = d * d, d ** 3
    # maps on basis
    mu = [A.mul[i][j] for i in range(d) for j in range(d)]                      # A(x)A -> A
    sig = [e(n2, j * d + i) for i in range(d) for j in range(d)]               # swap
    p13 = [e(n3, (i * d + 0) * d + j) for i in range(d) for j in range(d)]      # a(x)b -> a(x)1(x)b
    kermu = preimage(mu, [], n2, d)
    def ext12(I):   # I (x) A inside A(x)A(x)A
        return [tuple(v[(x // d)] if (x % d) == k else 0 for x in range(n3)) for v in I for k in range(d)]
    def ext23(I):   # A (x) I
        out = []
        for k in range(d):
            for v in I:
                w = [0] * n3
                for ij in range(n2):
                    if v[ij]:
                        w[k * n2 + ij] = v[ij]
                out.append(tuple(w))
        return out
    def eqclosure(I):
        while True:
            S = span([tuple(v[sig_index[x]] for x in range(n2)) for v in I], n2)
            T = preimage(p13, span(ext12(I) + ext23(I), n3), n2, n3)
            J = intersect(intersect(I, S, n2), T, n2)
            if len(J) == len(I):
                return I
            I = J
    sig_index = [ (x % d) * d + (x // d) for x in range(n2)]
    def invariants(I):
        f = [tuple((e(n2, i * d) [x] - e(n2, i)[x]) % P for x in range(n2)) for i in range(d)]  # a -> a(x)1 - 1(x)a
        return preimage(f, I, d, n2)
    found = 0
    for t in range(TRIALS):
        # a subalgebra B0 generated by 1 or 2 random non-units, its J_{B0}, plus 1 or 2 random elements of ker mu
        def rnd_nonunit():
            return tuple([0] + [random.randrange(P) for _ in range(d - 1)])
        bg = [rnd_nonunit() for _ in range(random.randint(1, 2))]
        B0 = [e(d, 0)] + bg
        while True:
            new = span(B0 + [times(A, u, v) for u in B0 for v in B0], d)
            if len(new) == len(span(B0, d)):
                break
            B0 = new
        B0 = span(B0, d)
        J0 = [tuple((sum(b[i] * e(n2, i * d)[x] for i in range(d)) - sum(b[i] * e(n2, i)[x] for i in range(d))) % P
                    for x in range(n2)) for b in B0]
        k = random.randint(1, 2)
        extra = [tuple(random.randrange(P) for _ in range(len(kermu))) for _ in range(k)]
        extra = [tuple(sum(g[i] * kermu[i][x] for i in range(len(kermu))) % P for x in range(n2)) for g in extra]
        gens = J0 + extra
        I0 = ideal(AA, gens)
        # optionally enlarge: random sum with more of kermu
        E = eqclosure(I0)
        B = invariants(E)
        JB = ideal(AA, [tuple((e(n2, 0) and 0) or 0 for _ in range(0))] if False else
                   [tuple((sum(b[i] * e(n2, i * d)[x] for i in range(d)) - sum(b[i] * e(n2, i)[x] for i in range(d))) % P
                          for x in range(n2)) for b in B])
        if len(JB) != len(E):
            found += 1
            print(f"COUNTEREXAMPLE {name} p={P} trial={t}: dim E={len(E)} dim J_B={len(JB)} dim B={len(B)}", flush=True)
            print("  generators of I0:", gens, flush=True)
            return True
    print(f"{name}: no counterexample in {TRIALS} trials", flush=True)
    return False

