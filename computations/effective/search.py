def all_monomial_algs(nvars, maxdim):
    """all down-closed monomial sets (order ideals) in nvars variables with 2..maxdim monomials"""
    cands = [e for e in itertools.product(range(maxdim), repeat=nvars) if sum(e) < maxdim]
    seen = set()
    def grow(S):
        key = frozenset(S)
        if key in seen:
            return
        seen.add(key)
        if len(S) >= 2:
            yield S
        if len(S) == maxdim:
            return
        for m in cands:
            if m in S:
                continue
            if all(tuple(m[:i] + (m[i] - 1,) + m[i + 1:]) in S for i in range(nvars) if m[i] > 0):
                yield from grow(S | {m})
    yield from grow({tuple([0] * nvars)})

