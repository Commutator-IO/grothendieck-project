# Polynomials: dict {exponent tuple: coeff}. Linear algebra mod p (p prime) or over Q via Fraction.
import itertools, sys
from fractions import Fraction
P = int(sys.argv[1]) if len(sys.argv)>1 else 0   # 0 = rationals
def norm(c):
    return c % P if P else c
def F(c): return Fraction(c) if not P else c % P
def inv(c): return pow(c,P-2,P) if P else 1/c
def add(a,b,s=1):
    r=dict(a)
    for m,c in b.items():
        r[m]=norm(r.get(m,0)+s*c)
        if r[m]==0: del r[m]
    return r
def mul(a,b):
    r={}
    for m1,c1 in a.items():
        for m2,c2 in b.items():
            m=tuple(i+j for i,j in zip(m1,m2)); r[m]=norm(r.get(m,0)+c1*c2)
            if r[m]==0: del r[m]
    return r
def var(i,n):
    e=[0]*n; e[i]=1; return {tuple(e):F(1)}
def const(c,n): return {tuple([0]*n):F(c)}
def monos(n,d):
    for c in itertools.combinations_with_replacement(range(n),d):
        e=[0]*n
        for i in c: e[i]+=1
        yield tuple(e)
def deg(p): return {sum(m) for m in p}
def homog_part(gens,n,d):
    """spanning set of degree-d part of ideal generated by homogeneous gens"""
    out=[]
    for g in gens:
        dg=sum(next(iter(g)))
        if dg<=d:
            for m in monos(n,d-dg): out.append(mul(g,{m:F(1)}))
    return out
def rank_and_member(vecs, target=None):
    # Gaussian elimination on dict vectors
    piv={}  # pivot monomial -> reduced vector
    def reduce(v):
        v=dict(v)
        changed=True
        while v:
            ms=[m for m in v if m in piv]
            if not ms: break
            m=ms[0]; c=v[m]; w=piv[m]
            v=add(v,{k:norm(c*x) for k,x in w.items()},-1)
        return v
    for v in vecs:
        v=reduce(v)
        if v:
            m=max(v); c=inv(v[m]); v={k:norm(c*x) for k,x in v.items()}
            # keep piv fully reduced lazily
            piv[m]=v
    if target is None: return len(piv)
    return len(piv), (len(reduce(target))==0)
# ring k[x1,x2,y1,y2,z1,z2] -> n=6, x=(0,1), y=(2,3), z=(4,5)
n=6
def X(i,blk): return var(2*blk+i,n)
def f1(b): return mul(X(0,b),X(0,b))
def f2(b): return add(mul(X(0,b),X(1,b)),mul(X(1,b),X(1,b)),-1)
def f3(b): return mul(mul(X(1,b),X(1,b)),X(1,b))
def ff(b,c):  # (x1 y2 - x2 y1) y2^3 with x=block b, y=block c
    w=add(mul(X(0,b),X(1,c)),mul(X(1,b),X(0,c)),-1)
    return mul(w,mul(mul(X(1,c),X(1,c)),X(1,c)))
def Igens(b,c):
    return [add(f1(b),f1(c),-1),add(f2(b),f2(c),-1),add(f3(b),f3(c),-1),ff(b,c)]
